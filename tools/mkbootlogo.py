#!/usr/bin/env python3
"""mkbootlogo.py - gera o patch 0334 (logo no centro da tela de boot do S7) a partir de um PNG.

Uso:
  python3 tools/mkbootlogo.py --base xnu/patches/0334-boot-logo.patch seu-logo.png --out 0334-boot-logo.patch
  python3 tools/mkbootlogo.py --base 0334-boot-logo.patch --out 0334-boot-logo.patch      (sem PNG: logo de teste, um anel)

--base: o patch 0334 que veio comigo (a parte fixa: rotina em start.s e files.arm64). Este script so troca o
        arquivo de dados osfmk/arm64/hero_bootlogo.s dentro dele.
--max : lado maior, em pixels (padrao 96, maximo 160). O logo e reduzido mantendo a proporcao e fica no centro.
Precisa do Pillow:  sudo pacman -S python-pillow
Formato: ate 255 cores + indice 0 = nao desenha (preto do fundo). Pixels pretos viram "nao desenhar".
"""
import argparse, sys

MARK = "diff --git a/osfmk/arm64/hero_bootlogo.s b/osfmk/arm64/hero_bootlogo.s"

def default_image(Image, ImageDraw):
    im = Image.new("RGBA", (96, 96), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.ellipse((6, 6, 89, 89), outline=(255, 255, 255, 255), width=6)
    d.ellipse((38, 38, 57, 57), fill=(0, 200, 255, 255))
    return im

def build(png, maxside):
    from PIL import Image, ImageDraw
    im = Image.open(png).convert("RGBA") if png else default_image(Image, ImageDraw)
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    im = Image.alpha_composite(bg, im).convert("RGB")
    if max(im.size) > maxside:
        k = maxside / max(im.size)
        im = im.resize((max(1, round(im.size[0] * k)), max(1, round(im.size[1] * k))), Image.LANCZOS)
    w, h = im.size
    q = im.quantize(colors=255, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:255 * 3]
    pal += [0] * (255 * 3 - len(pal))
    palette = [0] * 256
    for i in range(255):
        palette[i + 1] = 0xFF000000 | (pal[3 * i] << 16) | (pal[3 * i + 1] << 8) | pal[3 * i + 2]
    pixels = []
    for idx in q.tobytes():
        c = palette[idx + 1]
        pixels.append(0 if (c & 0xFFFFFF) == 0 else idx + 1)
    return w, h, palette, pixels

def asm_text(w, h, palette, pixels):
    L = ["/* (0334) Boot logo %dx%d, generated by mkbootlogo.py. Format: .long width, .long height, 256 x .long ARGB" % (w, h),
         " * palette, then width*height palette indexes (index 0 is not drawn). Read by La5_draw_logo in start.s. */",
         "\t.section __TEXT,__const", "\t.align\t2", "\t.globl\t_hero_bootlogo", "_hero_bootlogo:",
         "\t.long\t%d" % w, "\t.long\t%d" % h]
    for i in range(0, 256, 8):
        L.append("\t.long\t" + ", ".join("0x%08x" % c for c in palette[i:i + 8]))
    for i in range(0, len(pixels), 32):
        L.append("\t.byte\t" + ", ".join(str(p) for p in pixels[i:i + 32]))
    return L

def file_diff(lines):
    out = [MARK, "new file mode 100644", "index 0000000..1234567", "--- /dev/null", "+++ b/osfmk/arm64/hero_bootlogo.s",
           "@@ -0,0 +1,%d @@" % len(lines)]
    out += ["+" + l for l in lines]
    return "\n".join(out) + "\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("png", nargs="?")
    ap.add_argument("--base", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--max", type=int, default=96)
    a = ap.parse_args()
    if a.max > 160 or a.max < 8:
        sys.exit("--max entre 8 e 160")
    base = open(a.base).read()
    if MARK in base:
        base = base[:base.index(MARK)]
    w, h, palette, pixels = build(a.png, a.max)
    ncol = len({p for p in pixels if p})
    open(a.out, "w").write(base + file_diff(asm_text(w, h, palette, pixels)))
    print("logo %dx%d, %d cores, %d bytes de dados -> %s" % (w, h, ncol, w * h + 1032, a.out))

if __name__ == "__main__":
    main()
